export function formatCurrency(
  amountUsd: number,
  currencyCode: string,
  liveRates?: Record<string, number>
): string {
  const found = SUPPORTED_CURRENCIES.find((c) => c.code === currencyCode) || SUPPORTED_CURRENCIES[0];
  const rate = liveRates?.[currencyCode] ?? found.defaultRate;
  const converted = amountUsd * rate;
  const decimals = rate > 50 ? 0 : 2;
  return `${found.symbol}${converted.toLocaleString(undefined, {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })}`;
}

